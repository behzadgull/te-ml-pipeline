"""
NA12: draft of the results part of Section 4.5.1 and of Tables 12 and 13, generated from the committed outputs of the comparison run (summary.json with its added_after_run block, not_legible_counts.json).
Every number in the draft is read from those files; the words are a template and say only what the numbers say. Writes thesis_paper/docs/na12_results_draft.md.

Usage (repository root):  python thesis_paper/scripts/na12_make_results_draft.py [--run-dir thesis_paper/results/na12_comparison/<UTC>]
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import run_record as rr  # noqa: E402

RUN = "thesis_paper/results/na12_comparison/20261019T125259"
OUT = REPO / "thesis_paper" / "docs" / "na12_results_draft.md"
NAMES = {"10.1006/jssc.1995.1384": "Ohtaki et al. 1995", "10.1007/s11664-009-0666-x": "Shibasaki et al. 2009", "10.1021/acsaem.2c01936": "Sebastia-Luna et al. 2022",
         "10.1039/d0ce00702a": "Rajasekaran et al. 2020", "10.1063/1.1847723": "Ohta et al. 2005", "10.1080/14786435.2016.1263404": "Singh and Pandey 2016", "10.1109/ict.2006.331291": "Flahaut et al. 2006"}
SHORT = {"10.1006/jssc.1995.1384": "Ohtaki", "10.1007/s11664-009-0666-x": "Shibasaki", "10.1021/acsaem.2c01936": "Sebastia-Luna", "10.1039/d0ce00702a": "Rajasekaran", "10.1063/1.1847723": "Ohta",
         "10.1080/14786435.2016.1263404": "Singh", "10.1109/ict.2006.331291": "Flahaut"}
PROP = {"S": "S", "sigma": "σ", "kappa": "κ", "zT": "zT"}
ORDER = ("S", "sigma", "kappa", "zT")
LEVEL = {"exact": "exact", "cluster": "cluster"}


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def fs(x):
    return "n/a" if x is None else f"{x:+.3f}"


def table(header, rows):
    """A pipe table with contiguous rows (a blank line between rows would end the table)."""
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def paper_rows(doi, b, log, levels=("exact", "cluster")):
    rows = []
    for level in levels:
        for t in ORDER:
            v = b["by_property_and_level"][f"{t}_{level}"]
            if not v["n_compared"]:
                continue
            lg = log["by_property_and_level"].get(f"{t}_{level}") if t in ("sigma", "kappa") else None
            rows.append([NAMES[doi], level, PROP[t], v["n_compared"], f"{v['n_inside_band']} ({f3(v['fraction_inside_band'])})", f3(v["median_abs_rel_error"]),
                         f3(lg["median_abs_log10_ratio"]) if lg else "–", fs(lg["median_signed_log10_ratio"]) if lg else "–"])
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", default=RUN)
    args = ap.parse_args()
    d = REPO / args.run_dir
    s = json.loads((d / "summary.json").read_text(encoding="utf-8"))
    nl = json.loads((d / "not_legible_counts.json").read_text(encoding="utf-8"))
    add = s["added_after_run"]
    lg_head, lg_alt = add["log10_comparison"]["headline"], add["log10_comparison"]["neighbouring_bin"]["overall_independent_papers"]
    by = s["by_paper"]
    indep = {k: v for k, v in by.items() if not v["training_source"]}
    train = {k: v for k, v in by.items() if v["training_source"]}
    eps = s["relative_uncertainty"]
    n_win_i, n_win_t = sum(v["n_in_window"] for v in indep.values()), sum(v["n_in_window"] for v in train.values())
    ov = s["overall_independent_papers"]["by_property_and_level"]
    ovl = lg_head["overall_independent_papers"]["by_property_and_level"]
    es = s["edge_sensitivity"]
    evs = es["edge_values"]
    changing = [e for e in evs if e["status_changes"]]
    L = []
    L.append("# DRAFT (generated, not committed to the paper): NA12 results for Section 4.5.1 and Tables 12 and 13\n")
    L.append(f"Generated by `scripts/na12_make_results_draft.py` from `{args.run_dir}` (summary.json, including the block added after the run, and not_legible_counts.json). Every number is read from those files. Plain statements of the\n"
             "pre-registered report; no interpretation beyond what the numbers say.\n\n---\n")
    L.append("### 4.5.1 Literature validation: results\n")
    L.append(f"**What was compared.** {s['n_values_read']} literature values were read from the {len(by)} papers; after averaging the values of one sample, property and 25 K bin, {s['n_values_after_aggregation']} remained, and {s['n_in_window']} of these lie inside "
             f"300 K to 800 K and are compared ({s['n_cluster_level_only']} of the {s['n_values_after_aggregation']} values are compared at the cluster level only: those of {', '.join(NAMES[k] for k, v in sorted(by.items(), key=lambda kv: NAMES[kv[0]]) if v['n_cluster_level_only'])}). By DOI, "
             f"{len(train)} of the {len(by)} papers are training sources ({', '.join(NAMES[k] for k in sorted(train, key=lambda k: NAMES[k]))}) and {len(indep)} are independent ({', '.join(NAMES[k] for k in sorted(indep, key=lambda k: NAMES[k]))}); "
             f"{n_win_i} of the compared values are from independent papers and {n_win_t} from training-source papers, which are reported separately. The inside-the-band test uses the relative standard uncertainty of the round-robin measurements: "
             f"S {eps['S']:g}, σ {eps['sigma']:g}, κ {eps['kappa']:g}, zT {eps['zT']:g}.\n")
    L.append("**Independent papers, exact level (the main test).** The exact level compares a literature value with the held-out prediction for the same composition at the same temperature bin (the chemistry cluster of the composition is held out of the model that made the prediction). "
             "It exists only where the training table holds the composition at that bin. ")
    L.append("\n")
    for t in ORDER:
        rec = [(k, v["by_property_and_level"][f"{t}_exact"]) for k, v in indep.items() if v["by_property_and_level"][f"{t}_exact"]["n_compared"]]
        if not rec:
            L.append(f"- {PROP[t]}: no exact-level comparison.")
            continue
        ncmp, nin = sum(v["n_compared"] for _, v in rec), sum(v["n_inside_band"] for _, v in rec)
        det = ", ".join(f"{SHORT[k]} {v['n_inside_band']} of {v['n_compared']}" for k, v in rec)
        o = ov[f"{t}_exact"]
        txt = (f"- {PROP[t]}: {ncmp} values from {len(rec)} paper{'s' if len(rec) > 1 else ''}, {nin} inside the band ({det}). Papers weighing equally, the mean fraction inside the band is {f3(o['mean_over_papers_of_fraction_inside_band'])} and the median of the "
               f"papers' median absolute relative errors is {f3(o['median_over_papers_of_median_abs_rel_error'])}")
        if t in ("sigma", "kappa"):
            q = ovl[f"{t}_exact"]
            txt += f"; in log~10~, the median over papers of the median absolute ratio is {f3(q['median_over_papers_of_median_abs_log10_ratio'])} and of the signed median {fs(q['median_over_papers_of_signed_median_log10_ratio'])} (prediction minus literature)"
        L.append(txt + ".")
    L.append("\nTable 12 gives every paper.\n")
    L.append("**Independent papers, cluster level (a family-average comparison).** At the cluster level the prediction is the mean, over all training rows of the same chemistry cluster at that bin, of the held-out predictions; for a doped sample it is the average of the "
             "cluster the sample belongs to, not a prediction for that compound, and it is compared with the literature value of the sample. It is reported separately from the exact level. ")
    L.append("\n")
    for t in ORDER:
        rec = [(k, v["by_property_and_level"][f"{t}_cluster"]) for k, v in indep.items() if v["by_property_and_level"][f"{t}_cluster"]["n_compared"]]
        if not rec:
            continue
        ncmp, nin = sum(v["n_compared"] for _, v in rec), sum(v["n_inside_band"] for _, v in rec)
        det = ", ".join(f"{SHORT[k]} {v['n_inside_band']} of {v['n_compared']}" for k, v in rec)
        o = ov[f"{t}_cluster"]
        txt = (f"- {PROP[t]}: {ncmp} values from {len(rec)} paper{'s' if len(rec) > 1 else ''}, {nin} inside the band ({det}). Mean fraction inside {f3(o['mean_over_papers_of_fraction_inside_band'])}, median of the papers' medians {f3(o['median_over_papers_of_median_abs_rel_error'])}")
        if t in ("sigma", "kappa"):
            q = ovl[f"{t}_cluster"]
            txt += f"; log~10~: {f3(q['median_over_papers_of_median_abs_log10_ratio'])} (absolute), {fs(q['median_over_papers_of_signed_median_log10_ratio'])} (signed)"
        L.append(txt + ".")
    L.append("")
    L.append("**Training-source papers (reported separately, never pooled with the independent papers).** A paper whose DOI is among the DOIs of the training data is a training source; its comparison partly restates the cross-validation error. "
             "The rows of the training table with each paper's DOI are: " + "; ".join(f"{r['name']}: {r['rows_in_training_table']} rows ({r['distinct_compositions']} composition{'s' if r['distinct_compositions'] != 1 else ''}; "
             f"{r['compared_values_with_a_training_row_of_the_same_doi_and_composition']} of its {r['n_values']} values have a training row of the same DOI and composition)" for r in add["training_source_rows"].values()) + ". "
             "Their results per paper are in Table 12 (part B). Comparisons by level: ")
    parts = []
    for k in sorted(train, key=lambda k: NAMES[k]):
        b = train[k]
        cl = sum(v["n_compared"] for kk, v in b["by_property_and_level"].items() if kk.endswith("_cluster"))
        ex = sum(v["n_compared"] for kk, v in b["by_property_and_level"].items() if kk.endswith("_exact"))
        parts.append(f"{SHORT[k]} {ex} exact and {cl} cluster-level comparisons out of {b['n_in_window']} values inside the window")
    L.append("; ".join(parts) + ".\n")
    L.append(f"**Edge sensitivity.** {es['n_edge_values_in_window']} of the compared values lie within twice the calibration uncertainty of a 25 K bin edge and were also evaluated in the neighbouring bin. Table 13 gives the overall summary of the independent papers for the headline assignment and "
             f"for the neighbouring-bin assignment. {len(changing)} value-level results change (a changed in-band status, or no prediction in the neighbouring bin): "
             + ", ".join(f"{sum(1 for e in changing if e['lit_id'].startswith(p))} of {name}" for p, name in (("OHTAKI", "Ohtaki et al."), ("OH2005", "Ohta et al."), ("RJ2020", "Rajasekaran et al."), ("SH2009", "Shibasaki et al."), ("SG2017", "Singh and Pandey"), ("SL2022", "Sebastia-Luna et al."), ("FL", "Flahaut et al."))
                         if sum(1 for e in changing if e['lit_id'].startswith(p))))
    L.append("")
    th, tn = es["training_source_headline"], es["training_source_neighbouring_bin"]
    chg = []
    for doi in th:
        for kk, v in th[doi]["by_property_and_level"].items():
            w = tn[doi]["by_property_and_level"][kk]
            if v["n_compared"] and (v["n_inside_band"] != w["n_inside_band"] or abs((v["median_abs_rel_error"] or 0) - (w["median_abs_rel_error"] or 0)) > 1e-9):
                chg.append(f"{SHORT[doi]} {PROP[kk.split('_')[0]]} {kk.split('_')[1]}: {v['n_inside_band']} of {v['n_compared']} inside the band becomes {w['n_inside_band']} of {w['n_compared']}, the median absolute relative error {f3(v['median_abs_rel_error'])} becomes {f3(w['median_abs_rel_error'])}")
    L.append("Among the training-source papers, the neighbouring-bin run changes " + ("; ".join(chg) if chg else "nothing") + ".\n")
    n_gate = {k: v["by_kind"] for k, v in nl.items()}
    L.append("**Markers not read.** The digitised figures of " + ", ".join(f"{k} ({v['entries']} entries: {v['by_kind']['removed by a gate']['total']} markers removed by a gate, {v['by_kind']['unplaceable click']['total']} unplaceable clicks, "
             f"{v['by_kind']['empty derived column']['total']} empty derived columns)" for k, v in nl.items()) + "; the vector figures (Sebastia-Luna et al., Singh and Pandey, Flahaut et al., Shibasaki et al.) have no such list.\n")
    ctx = add["NOT_PRE_REGISTERED_context_rung_errors"]["by_property"]
    L.append("**Context (not pre-registered; added after the result).** For comparison with the errors above, the committed chemistry-cluster out-of-fold predictions of the rung (every prediction of the 5 repeats counted, not averaged per bin as the NA12 predictions are) have a median absolute relative error of "
             + ", ".join(f"{f3(ctx[t]['median_abs_rel_error'])} for {PROP[t]}" for t in ORDER) + " and a median absolute log~10~ ratio of "
             + ", ".join(f"{f3(ctx[t]['median_abs_log10_ratio'])} for {PROP[t]} (signed median {fs(ctx[t]['median_signed_log10_ratio'])})" for t in ("sigma", "kappa")) + ".\n")
    L.append("\n**Table 12.** Comparison of out-of-fold predictions with published measurements, per paper. n: values compared; inside: values whose absolute relative error is within the relative uncertainty of the measurement (S 0.06, σ 0.08, κ 0.11, zT 0.19), with the fraction; "
             "median abs. rel. error: median absolute relative error (linear units); log~10~ ratio: median absolute and signed median of log~10~(prediction) − log~10~(literature) for σ and κ. Exact level: the same composition at the same bin; cluster level: the mean of the held-out predictions of the sample's chemistry cluster at that bin (a family average).\n")
    hdr = ["Paper", "Level", "Property", "n", "Inside (fraction)", "Median abs. rel. error", "Median abs. log~10~ ratio", "Signed median log~10~ ratio"]
    L.append("*Part A: independent papers, exact level first.*\n")
    rows = []
    for level in ("exact", "cluster"):
        for k in sorted(indep, key=lambda k: NAMES[k]):
            rows += paper_rows(k, indep[k], lg_head["by_paper"][k], levels=(level,))
    L.append(table(hdr, rows) + "\n")
    orows = []
    for level in ("exact", "cluster"):
        for t in ORDER:
            o = ov[f"{t}_{level}"]
            if not o["n_papers_with_comparisons"]:
                continue
            q = ovl.get(f"{t}_{level}") if t in ("sigma", "kappa") else None
            orows.append([level, PROP[t], o["n_papers_with_comparisons"], f3(o["mean_over_papers_of_fraction_inside_band"]), f3(o["median_over_papers_of_median_abs_rel_error"]),
                          f3(q["median_over_papers_of_median_abs_log10_ratio"]) if q else "–", fs(q["median_over_papers_of_signed_median_log10_ratio"]) if q else "–"])
    L.append("\n*Overall, independent papers (papers weigh equally: the mean over papers of the fraction inside the band; the median over papers of each paper's median).*\n")
    L.append(table(["Level", "Property", "Papers", "Mean fraction inside", "Median of median abs. rel. error", "Median of median abs. log~10~ ratio", "Median of signed median log~10~ ratio"], orows) + "\n")
    L.append("\n*Part B: training-source papers (not pooled with part A).*\n")
    rows = []
    for k in sorted(train, key=lambda k: NAMES[k]):
        rows += paper_rows(k, train[k], lg_head["by_paper"][k])
    L.append(table(hdr, rows) + "\n")
    L.append("\n**Table 13.** Edge sensitivity: the overall summary of the independent papers with every edge value evaluated in its floor bin (headline) and in its neighbouring bin.\n")
    erows = []
    for level in ("exact", "cluster"):
        for t in ORDER:
            h = es["headline_overall_independent_papers"]["by_property_and_level"][f"{t}_{level}"]
            a = es["neighbouring_bin_overall_independent_papers"]["by_property_and_level"][f"{t}_{level}"]
            if not h["n_papers_with_comparisons"]:
                continue
            qh = ovl.get(f"{t}_{level}") if t in ("sigma", "kappa") else None
            qa = lg_alt["by_property_and_level"].get(f"{t}_{level}") if t in ("sigma", "kappa") else None
            erows.append([level, PROP[t], f3(h["mean_over_papers_of_fraction_inside_band"]), f3(a["mean_over_papers_of_fraction_inside_band"]), f3(h["median_over_papers_of_median_abs_rel_error"]), f3(a["median_over_papers_of_median_abs_rel_error"]),
                          f3(qh["median_over_papers_of_median_abs_log10_ratio"]) if qh else "–", f3(qa["median_over_papers_of_median_abs_log10_ratio"]) if qa else "–"])
    L.append(table(["Level", "Property", "Fraction inside, headline", "Fraction inside, neighbouring bin", "Median abs. rel. error, headline", "Median abs. rel. error, neighbouring bin", "Median abs. log~10~ ratio, headline", "Median abs. log~10~ ratio, neighbouring bin"], erows) + "\n")
    prov = rr.provenance({"summary_json": str(d / "summary.json"), "not_legible_counts": str(d / "not_legible_counts.json")}, __file__)
    L.append(f"\n---\nGenerated at commit `{prov['git_head']}` (tree clean: {prov['tree_clean']}) from summary.json SHA256 `{prov['inputs']['summary_json']['sha256']}`.\n")
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
